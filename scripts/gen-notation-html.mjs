// Generates apps/app/src/notation/notationHtml.generated.ts (gitignored): a self-contained HTML page for the
// Android WebView with VexFlow (+ embedded Bravura font) and the shared renderScore() inlined. The app posts
// the score in with postMessage; the page posts back {type:'height'|'error'}. Runs on postinstall.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import ts from 'typescript';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const require = createRequire(path.join(root, 'apps/app/package.json'));
const vexflowJs = fs.readFileSync(require.resolve('vexflow/bravura'), 'utf8');
if (!vexflowJs.includes('t.VexFlow=e()')) throw new Error('unexpected vexflow/bravura bundle format (no VexFlow global)');

const src = fs.readFileSync(path.join(root, 'apps/app/src/notation/renderScore.ts'), 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext } }).outputText
  .replace(/^export /gm, '')
  .replace(/^\/\/# sourceMappingURL.*$/m, '');
if (/^\s*import /m.test(js)) throw new Error('renderScore.ts must not have runtime imports');

const page = `<!doctype html><html><head><meta charset="utf-8">
<link rel="icon" href="data:,">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1">
<style>html,body{margin:0;padding:0;background:#fff;overflow-x:auto}#err{color:#b00020;font:14px sans-serif}</style>
</head><body><div id="n"></div><div id="err"></div>
<script>${vexflowJs.replace(/<\/script/gi, '<\\/script')}</script>
<script>
${js}
(function () {
  var post = function (m) { if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(JSON.stringify(m)); };
  var fontsReady = (document.fonts && document.fonts.load) ? document.fonts.load('30px Bravura').catch(function () {}) : Promise.resolve();
  var last = null;
  function draw() {
    var el = document.getElementById('n'), err = document.getElementById('err');
    err.textContent = '';
    if (!last) { el.innerHTML = ''; post({ type: 'height', height: 0 }); return; }
    try {
      var h = renderScore(window.VexFlow, el, last, document.documentElement.clientWidth || 360);
      post({ type: 'height', height: h, notes: el.querySelectorAll('.vf-stavenote').length });
    } catch (e) {
      err.textContent = 'Notation render error: ' + (e && e.message || e);
      post({ type: 'error', message: String(e && e.message || e) });
    }
  }
  function onMessage(ev) {
    var msg; try { msg = JSON.parse(ev.data); } catch (e) { return; }
    if (!msg || msg.type !== 'score') return;
    last = msg.score;
    fontsReady.then(draw);
  }
  window.addEventListener('message', onMessage);
  document.addEventListener('message', onMessage); // Android react-native-webview
  window.addEventListener('resize', function () { fontsReady.then(draw); });
  fontsReady.then(function () { post({ type: 'ready' }); });
})();
</script></body></html>`;

const out = path.join(root, 'apps/app/src/notation/notationHtml.generated.ts');
fs.writeFileSync(out, `// GENERATED by scripts/gen-notation-html.mjs. Do not edit; not committed.\nconst html: string = ${JSON.stringify(page)};\nexport default html;\n`);
console.log(`wrote ${path.relative(root, out)} (${(page.length / 1024).toFixed(0)} KiB page)`);
