import { useCallback, useEffect, useRef, useState } from 'react';
import { Text, View } from 'react-native';
import { WebView, type WebViewMessageEvent } from 'react-native-webview';
import type { Score } from '@guitar-tabs/core';
import notationHtml from './notation/notationHtml.generated';

// react-native-webview declares `class WebView<P = undefined>` with props `WebViewProps & P`; under strict null
// checks `& undefined` collapses the props to `never`, so instantiate it with an empty props extension.
const Web = WebView<object>;
type Web = WebView<object>;

/**
 * Native (Android) notation: VexFlow + Bravura run inside a local WebView page (generated by
 * scripts/gen-notation-html.mjs from the same renderScore() the web build uses). The score goes in via
 * postMessage; the page reports its drawn height back so the WebView can size itself.
 */
export default function NotationView({ score }: { score: Score | null }) {
  const web = useRef<Web>(null);
  const [ready, setReady] = useState(false);
  const [height, setHeight] = useState(0);
  const [error, setError] = useState<string | null>(null);

  const send = useCallback(() => {
    web.current?.postMessage(JSON.stringify({ type: 'score', score }));
  }, [score]);

  useEffect(() => { if (ready) send(); }, [ready, send]);

  const onMessage = useCallback((e: WebViewMessageEvent) => {
    let msg: { type?: string; height?: number; message?: string };
    try { msg = JSON.parse(e.nativeEvent.data); } catch { return; }
    if (msg.type === 'ready') setReady(true);
    else if (msg.type === 'height') { setError(null); setHeight(Math.ceil(msg.height ?? 0)); }
    else if (msg.type === 'error') setError(msg.message ?? 'unknown error');
  }, []);

  if (!score) return null;
  return (
    <View>
      <Web
        ref={web}
        testID="notation"
        originWhitelist={['*']}
        source={{ html: notationHtml, baseUrl: 'about:blank' }}
        onMessage={onMessage}
        onContentProcessDidTerminate={() => setReady(false)}
        onRenderProcessGone={() => { setReady(false); web.current?.reload(); }}
        javaScriptEnabled
        domStorageEnabled={false}
        allowFileAccess={false}
        setSupportMultipleWindows={false}
        // only the inline page itself; never navigate anywhere else
        onShouldStartLoadWithRequest={(r: { url: string }) => r.url === 'about:blank'}
        scrollEnabled={false}
        nestedScrollEnabled
        style={{ height: Math.max(height, 20), backgroundColor: '#fff' }}
      />
      {error && <Text style={{ color: '#b00020' }}>Notation render error: {error}</Text>}
    </View>
  );
}
